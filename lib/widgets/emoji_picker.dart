  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: _emojiCategories.length, vsync: this);
    _filteredEmojis = _getAllEmojis();
  }

  @override
  void dispose() {
    _tabController.dispose();
    _searchController.dispose();
    super.dispose();
  }

  List<String> _getAllEmojis() {
    List<String> allEmojis = [];
    for (List<String> emojis in _emojiCategories.values) {
      allEmojis.addAll(emojis);
    }
    return allEmojis;
  }

  void _filterEmojis(String query) {
    setState(() {
      _searchQuery = query.toLowerCase();
      if (_searchQuery.isEmpty) {
        _filteredEmojis = _getAllEmojis();
      } else {
        _filteredEmojis = _getAllEmojis().where((emoji) {
          // Simple search - you could enhance this with emoji names/descriptions
          return emoji.contains(_searchQuery) || 
                 _getEmojiDescription(emoji).toLowerCase().contains(_searchQuery);
        }).toList();
      }
    });
  }

  String _getEmojiDescription(String emoji) {
    // Basic emoji descriptions for search
    final descriptions = {
      '😀': 'grinning face',
      '😂': 'laughing crying',
      '❤️': 'red heart',
      '👍': 'thumbs up',
      '😍': 'heart eyes',
      '😊': 'smiling face',
      '🎉': 'party popper',
      '🔥': 'fire',
      '💯': 'hundred points',
      '✨': 'sparkles',
    };
    return descriptions[emoji] ?? emoji;
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    return Container(
      height: 400,
      decoration: BoxDecoration(
        color: isDark ? Colors.grey[900] : Colors.white,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(20)),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.1),
            blurRadius: 10,
            offset: const Offset(0, -5),
          ),
        ],
      ),
      child: Column(
        children: [
          // Header
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: isDark ? Colors.grey[800] : Colors.grey[100],
              borderRadius: const BorderRadius.vertical(top: Radius.circular(20)),
            ),
            child: Row(
              children: [
                Text(
                  'Emojis',
                  style: TextStyle(
                    fontSize: 18,
                    fontWeight: FontWeight.bold,
                    color: isDark ? Colors.white : Colors.black87,
                  ),
                ),
                const Spacer(),
                IconButton(
                  onPressed: widget.onClose,
                  icon: Icon(
                    Icons.close,
                    color: isDark ? Colors.white : Colors.black87,
                  ),
                ),
              ],
            ),
          ),
          
          // Search bar
          Padding(
            padding: const EdgeInsets.all(16),
            child: TextField(
              controller: _searchController,
              onChanged: _filterEmojis,
              decoration: InputDecoration(
                hintText: 'Search emojis...',
                prefixIcon: const Icon(Icons.search),
                border: OutlineInputBorder(
                  borderRadius: BorderRadius.circular(25),
